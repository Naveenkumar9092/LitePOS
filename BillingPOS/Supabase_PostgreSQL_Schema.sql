-- Automatic UpdatedAtUtc Timestamp Update Function
CREATE OR REPLACE FUNCTION update_updated_at_column()
RETURNS TRIGGER AS $$
BEGIN
    NEW."UpdatedAtUtc" = CURRENT_TIMESTAMP AT TIME ZONE 'UTC';
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- Sequential Invoice Number Generator (Per-Company & Per-Shop Isolated)
CREATE OR REPLACE FUNCTION generate_next_invoice_number(p_company_id BIGINT, p_shop_id BIGINT)
RETURNS VARCHAR(50) AS $$
DECLARE
    v_prefix VARCHAR(20);
    v_today VARCHAR(8);
    v_count INT;
    v_new_inv VARCHAR(50);
BEGIN
    v_today := TO_CHAR(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYYMMDD');
    v_prefix := 'INV-' || v_today || '-';
    
    SELECT COUNT(*) + 1 INTO v_count
    FROM "Invoices"
    WHERE "CompanyId" = p_company_id 
      AND "ShopId" = p_shop_id 
      AND "InvoiceNumber" LIKE v_prefix || '%';
      
    v_new_inv := v_prefix || LPAD(v_count::TEXT, 5, '0');
    RETURN v_new_inv;
END;
$$ LANGUAGE plpgsql;

